print("===== Assignment Operators =====")

x = 20

print(f"Initial value: {x}")

x += 5
print(f"After += 5 : {x}")

x -= 3
print(f"After -= 3 : {x}")

x *= 2
print(f"After *= 2 : {x}")

x /= 4
print(f"After /= 4 : {x}")

x //= 2
print(f"After //= 2 : {x}")

x %= 3
print(f"After %= 3 : {x}")

x **= 2
print(f"After **= 2 : {x}")