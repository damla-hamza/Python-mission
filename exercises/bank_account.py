balance -= 300
print(f"\n Withdraw: 300")
print(f"Balance: {balance}")

balance *= 2
print(f"\n Bonus x2")
print(f"Balance: {balance}")

balance /= 2
print(f"\n Divide by 2")
print(f"Balance: {balance}")    

